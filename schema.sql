-- 10,000 users, 10 posts each, 5 comments on every post. Timestamps are fixed so every app answers byte for byte
-- the same way across runs.
CREATE TABLE users (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT        NOT NULL,
  email      TEXT        NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE posts (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER     NOT NULL REFERENCES users (id),
  title      TEXT        NOT NULL,
  body       TEXT        NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE comments (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id    INTEGER     NOT NULL REFERENCES posts (id),
  author     TEXT        NOT NULL,
  body       TEXT        NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX posts_user_id ON posts (user_id);
CREATE INDEX comments_post_id ON comments (post_id);

INSERT INTO users (id, name, email, created_at)
SELECT i, 'User ' || i, 'user' || i || '@example.com', timestamptz '2026-01-01' + i * interval '1 minute'
FROM generate_series(1, 10000) AS i;
INSERT INTO posts (id, user_id, title, body, created_at)
SELECT p, (p - 1) / 10 + 1, 'Post ' || p,
       repeat('A post body with a few sentences in it. ', 4),
       timestamptz '2026-02-01' + p * interval '1 minute'
FROM generate_series(1, 100000) AS p;
INSERT INTO comments (id, post_id, author, body, created_at)
SELECT c, (c - 1) / 5 + 1, 'User ' || (c % 10000 + 1), 'Nice post, thanks for writing it.',
       timestamptz '2026-03-01' + c * interval '1 minute'
FROM generate_series(1, 500000) AS c;
SELECT setval(pg_get_serial_sequence('users', 'id'), 10000);
SELECT setval(pg_get_serial_sequence('posts', 'id'), 100000);
SELECT setval(pg_get_serial_sequence('comments', 'id'), 500000);
